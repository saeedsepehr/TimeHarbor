type Word = keyof typeof words;
const languages: Language[] = ["en", "fa", "ar", "es", "fr", "de", "zh"];
export const languageNames: Record<Language, string> = {
  en: "English",
  fa: "فارسی",
  ar: "العربية",
  es: "Español",
  fr: "Français",
  de: "Deutsch",
  zh: "中文",
};
export function t(key: Word, language: Language): string {
  return words[key][languages.indexOf(language)] ?? words[key][0];
}
export function duration(ms: number, language: Language): string {
  const total = Math.max(0, Math.floor(ms / 60_000)),
    h = Math.floor(total / 60),
    m = total % 60;
  const n = new Intl.NumberFormat(language);
  return h
    ? `${n.format(h)} ${t("hours", language)} ${n.format(m)} ${t("minutes", language)}`
    : `${n.format(m)} ${t("minutes", language)}`;
}
